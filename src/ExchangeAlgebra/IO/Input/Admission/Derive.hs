-- | Derive ledger views and reporting values in the IO input layer from admitted
-- data. This module uses trial-balance validation and presentation; callers of
-- the public admission API consume its readouts and cannot supply balances.
-- Read the source getters before the derivation path.
module ExchangeAlgebra.IO.Input.Admission.Derive
    ( -- * Transaction notes
      admissionKey
    , admissionRole
    , admissionProvenance
    , admissionStage
      -- * Read-only observations
    , admittedJournal
    , admittedCalls
    , restrictAdmitted
    , admittedTrialBalance
    , admittedAdjustedTrialBalance
    , admittedFinancialStatements
    , admittedClosingStatements
      -- * Derivation
    , deriveTrialBalance
    , presentAdmitted
    ) where

import Data.List.NonEmpty (NonEmpty(..))
import qualified Data.Map.Strict as Map
import qualified Data.Set as Set

import ExchangeAlgebra.IO.Input.Admission.Catalog (kindStage, roleStage)
import qualified ExchangeAlgebra.Journal.Core as Journal
import ExchangeAlgebra.IO.Input.Admission.Representation
import ExchangeAlgebra.Accounting.Transaction (Entry, TxKey)
import ExchangeAlgebra.IO.Input.Admission.Workflow
import qualified ExchangeAlgebra.Accounting.Statements.Presentation as Presentation
import qualified ExchangeAlgebra.Accounting.TrialBalance.Validation as TrialBalance
import ExchangeAlgebra.Algebra.Value (MoneyDecimal)

-- * Transaction notes

-- | The exact entity-period-transaction key of an admitted transaction.
admissionKey :: AdmissionNote -> TxKey
admissionKey (AdmissionNote key _ _) = key

-- | The role fixed by the trusted registry for this transaction.
admissionRole :: AdmissionNote -> Role
admissionRole (AdmissionNote _ role _) = role

-- | The origin established by admission: a trusted fact, submitted postings,
-- or a catalog call with its operation kind.
admissionProvenance :: AdmissionNote -> Provenance
admissionProvenance (AdmissionNote _ _ origin) = origin

-- | The library-controlled processing stage. A transaction generated by a
-- catalog call takes the stage of its operation kind (for example the
-- equity-method balance query is 'QueryStage' although its role is
-- 'Adjustment'); every other transaction takes the stage of its role.
-- This is the stage admission used when it processed the transaction.
admissionStage :: AdmissionNote -> Stage
admissionStage (AdmissionNote _ role origin) = case origin of
    CatalogProvenance _ kind -> kindStage kind
    _ -> roleStage role

-- * Read-only observations

-- | Observe the accepted journal: one note per admitted transaction, with
-- every original posting. Transactions without postings, such as a generated
-- transaction whose computed amount is zero, do not appear. Its ordinary
-- mutators produce unadmitted journals and cannot reconstruct an
-- t'Admitted' value.
--
-- The 0.5.x snapshots are restrictions of this journal by stage:
--
-- @
-- DuringPeriod  restrictAdmitted ((<= OrdinaryStage) . admissionStage)
-- Adjusted      restrictAdmitted ((<= ConsolidationStage) . admissionStage)
-- Closed        the admitted value itself
-- @
admittedJournal :: Admitted -> AdmissionJournal
admittedJournal (Admitted journal _ _) = journal

-- | Observe library-established origins and successful query projections,
-- one record per executed call in execution order.
admittedCalls :: Admitted -> [CallAudit]
admittedCalls (Admitted _ calls _) = calls

-- | Keep the transactions whose note satisfies the predicate. The call audit
-- is kept whole: after restriction it no longer corresponds one to one with
-- the journal's notes, since a call can generate a transaction that the
-- predicate drops and a closing call can generate several notes.
-- Restricting by entity and then deriving a trial balance keeps the strict
-- policy unchanged; for example inter-office accounts of one entity are not
-- eliminated by the restriction. The predicate also applies to accepted
-- transactions without postings: a dropped closing transaction, empty or not,
-- no longer counts when trial-balance derivation chooses AfterClosing, and a
-- kept one still counts. Hence
-- @restrictAdmitted p . restrictAdmitted q = restrictAdmitted (\\n -> p n && q n)@
-- and @restrictAdmitted (const True)@ is the identity.
restrictAdmitted :: (AdmissionNote -> Bool) -> Admitted -> Admitted
restrictAdmitted predicate (Admitted journal calls notes) =
    Admitted (Journal.filterWithNote (\note _ -> predicate note) journal)
        calls (Set.filter predicate notes)

-- | Read the final validated trial-balance element without granting admission
-- authority to any transformed result. Net balances use the existing
-- @accountBalances@ readout; original postings remain available in the ledger.
admittedTrialBalance :: AdmittedTrialBalance -> Entry
admittedTrialBalance (AdmittedTrialBalance _ final _) =
    TrialBalance.validatedTrialBalance final

-- | Read the validated adjusted balance before closing removes revenue and
-- expense balances. The snapshot comes only from the admitted journal.
admittedAdjustedTrialBalance :: AdmittedTrialBalance -> Entry
admittedAdjustedTrialBalance (AdmittedTrialBalance _ _ adjusted) =
    TrialBalance.validatedTrialBalance adjusted

-- | Observe presentation of the adjusted snapshot, including nominal accounts.
admittedFinancialStatements :: AdmittedStatements -> Presentation.FinancialStatements MoneyDecimal
admittedFinancialStatements (AdmittedStatements _ adjusted _) = adjusted

-- | Observe presentation of the final snapshot, after closing when supplied.
admittedClosingStatements :: AdmittedStatements -> Presentation.FinancialStatements MoneyDecimal
admittedClosingStatements (AdmittedStatements _ _ final) = final

-- * Derivation

-- | Accumulate failures from two independent snapshot validations.
combineResults
    :: Either (NonEmpty error) left
    -> Either (NonEmpty error) right
    -> Either (NonEmpty error) (left, right)
combineResults (Right left) (Right right) = Right (left, right)
combineResults (Left left) (Left right) = Left (left <> right)
combineResults (Left errors) _ = Left errors
combineResults _ (Left errors) = Left errors

-- | Validate the adjusted and final journals using the existing strict policy.
-- The adjusted journal is the restriction to stages up to
-- 'ConsolidationStage', validated BeforeClosing. The final journal is the
-- whole admitted journal; it is AfterClosing if the accepted transactions
-- kept by every restriction so far include a closing transaction (with or
-- without postings), otherwise
-- BeforeClosing. No external balance,
-- explanation, or reclassification can be injected into this path.
-- Any admitted transaction with the Closing role selects AfterClosing for the
-- final snapshot, including submitted postings authorized by
-- @SupplySubmission Closing@ in the trusted registry. This decision does not
-- require the transaction to originate from a catalog closing operation.
--
-- Derivation combines all entities and reporting periods in the admitted journal;
-- acceptance proves provenance and balance, not the economic correctness of
-- consolidation or the appropriateness of combining reporting periods.
-- A successful admission does not guarantee success here: strict snapshot
-- validation can return 'Left' independently of admission's checks.
deriveTrialBalance
    :: Admitted
    -> Either (NonEmpty (TrialBalance.TBFinding MoneyDecimal)) AdmittedTrialBalance
deriveTrialBalance admitted@(Admitted journal _ notes) = do
    (finalBalance, adjustedBalance) <- combineResults
        (validate finalStage journal)
        (validate TrialBalance.BeforeClosing adjusted)
    Right (AdmittedTrialBalance admitted finalBalance adjustedBalance)
  where
    adjusted = Journal.filterWithNote (\note _ -> admissionStage note <= ConsolidationStage) journal
    finalStage
        | any ((== Closing) . admissionRole) notes = TrialBalance.AfterClosing
        | otherwise = TrialBalance.BeforeClosing
    validate
        :: TrialBalance.TrialBalanceStage
        -> AdmissionJournal
        -> Either (NonEmpty (TrialBalance.TBFinding MoneyDecimal))
                  (TrialBalance.ValidatedTrialBalance MoneyDecimal)
    validate stage source = TrialBalance.validateTrialBalance TrialBalance.strictTrialBalancePolicy
        (TrialBalance.TrialBalanceInput (Journal.toAlg source) stage Map.empty [] Set.empty)

-- | Present the validated adjusted and final snapshots. A reporting context
-- can control supported classifications, but cannot replace either balance.
-- The caller chooses the context; no default is inferred from admission.
-- Presentation returns its own 'Either' and can fail even after trial-balance
-- derivation succeeds. See 'Presentation.jcciSecondGradeContext' for the
-- JGAAP and JCCI grade-2 starting context and its empty instruction lists.
presentAdmitted
    :: Presentation.ReportingContext MoneyDecimal
    -> AdmittedTrialBalance
    -> Either (NonEmpty (Presentation.PresentationIssue MoneyDecimal)) AdmittedStatements
presentAdmitted context accepted@(AdmittedTrialBalance _ final adjusted) = do
    (adjustedStatements, finalStatements) <- combineResults
        (Presentation.present context adjusted)
        (Presentation.present context final)
    Right (AdmittedStatements accepted adjustedStatements finalStatements)

